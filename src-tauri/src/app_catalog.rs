#[cfg(windows)]
mod windows_impl {
    use super::{classify, dedupe, InstalledApp};
    use windows::core::{w, Interface, GUID, PWSTR};
    use windows::Win32::Foundation::PROPERTYKEY;
    use windows::Win32::System::Com::{
        CoInitializeEx, CoTaskMemFree, CoUninitialize, COINIT_APARTMENTTHREADED,
    };
    use windows::Win32::UI::Shell::{
        BHID_EnumItems, IEnumShellItems, IShellItem, IShellItem2, SHCreateItemFromParsingName,
        SIGDN_NORMALDISPLAY,
    };

    /// The two shell properties this module reads, declared here rather than
    /// imported.
    ///
    /// The `windows` crate files them under a feature (`Win32_Storage_EnhancedStorage`)
    /// whose name has nothing to do with what they are, and turning it on — plus
    /// `Win32_UI_Shell_PropertiesSystem` — meant five more lines in the
    /// Handy-derived `Cargo.toml`, which is the one place Grain is trying not to
    /// grow. Two constants cost less than two crate features, and a property key
    /// is a published, frozen identifier: these are the values in the
    /// `System.Link.TargetParsingPath` and `System.AppUserModel.ID` docs, and
    /// they cannot change without breaking every shell client on Windows.
    const PKEY_LINK_TARGET_PARSING_PATH: PROPERTYKEY = PROPERTYKEY {
        fmtid: GUID::from_u128(0xb9b4b3fc_2b51_4a42_b5d8_324146afcf25),
        pid: 2,
    };
    const PKEY_APP_USER_MODEL_ID: PROPERTYKEY = PROPERTYKEY {
        fmtid: GUID::from_u128(0x9f4c2855_9f79_4b39_a8d0_e1d42de1d5f3),
        pid: 5,
    };

    /// Items per `Next` call. One COM round-trip per app would double the cost
    /// of the walk for nothing; a machine's whole Start menu is a few hundred.
    const BATCH: usize = 32;

    /// Refuses to run away on a pathological namespace. A real machine is in the
    /// low hundreds, so this can only ever be hit by something going wrong.
    const MAX_ITEMS: usize = 4096;

    pub fn enumerate() -> Vec<InstalledApp> {
        unsafe {
            // Our own thread, so our own apartment — same reasoning as the icon
            // resolver: nothing else in this process has initialised COM here.
            let co = CoInitializeEx(None, COINIT_APARTMENTTHREADED);
            let apps = walk();
            if co.is_ok() {
                CoUninitialize();
            }
            dedupe(apps)
        }
    }

    unsafe fn walk() -> Vec<InstalledApp> {
        let Ok(folder) =
            SHCreateItemFromParsingName::<_, _, IShellItem>(w!("shell:AppsFolder"), None)
        else {
            return Vec::new();
        };
        let Ok(items) = folder.BindToHandler::<_, IEnumShellItems>(None, &BHID_EnumItems) else {
            return Vec::new();
        };

        let mut out = Vec::new();
        let mut seen = 0usize;
        loop {
            // A fresh buffer each pass: `Next` writes raw pointers over the
            // slice without dropping what was there, so reusing one would leak
            // an interface per batch.
            let mut batch: [Option<IShellItem>; BATCH] = std::array::from_fn(|_| None);
            let mut fetched = 0u32;
            // S_FALSE is a success code and means "fewer than asked for", so the
            // count — not the HRESULT — is what ends the walk.
            if items.Next(&mut batch, Some(&mut fetched)).is_err() || fetched == 0 {
                break;
            }
            for item in batch.into_iter().take(fetched as usize).flatten() {
                if let Some(app) = row(&item) {
                    out.push(app);
                }
            }
            seen += fetched as usize;
            if (fetched as usize) < BATCH || seen >= MAX_ITEMS {
                break;
            }
        }
        out
    }

    /// One shell item → one catalogue row, or `None`.
    unsafe fn row(item: &IShellItem) -> Option<InstalledApp> {
        let name = take(item.GetDisplayName(SIGDN_NORMALDISPLAY).ok()?)?;
        // The properties live on IShellItem2; an item that does not support it
        // cannot be identified, which is a reason to skip it rather than guess.
        let item2: IShellItem2 = item.cast().ok()?;
        // Both are absent on plenty of entries — a desktop app has no packaged
        // identity, a packaged app has no target — so a failure here is the
        // normal case and `classify` is what decides which combination is usable.
        let target = item2
            .GetString(&PKEY_LINK_TARGET_PARSING_PATH)
            .ok()
            .and_then(|p| take(p))
            .unwrap_or_default();
        let aumid = item2
            .GetString(&PKEY_APP_USER_MODEL_ID)
            .ok()
            .and_then(|p| take(p))
            .unwrap_or_default();
        classify(&name, &target, &aumid)
    }

    /// Copy a shell-allocated string out and free it. Every one of these comes
    /// from an API documented as transferring ownership, so the free is not
    /// optional — a Start menu's worth of leaks per picker open would be real.
    unsafe fn take(p: PWSTR) -> Option<String> {
        if p.is_null() {
            return None;
        }
        let s = p.to_string().ok();
        CoTaskMemFree(Some(p.0 as *const std::ffi::c_void));
        s.filter(|s| !s.trim().is_empty())
    }
}
